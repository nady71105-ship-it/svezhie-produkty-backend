import { Router } from 'express';
import { pool } from '../db/pool.js';
import { requireTelegramAuth } from '../middleware/auth.js';

export const consentsRouter = Router();

// ── Тексты согласий ──────────────────────────────────────────────────────
// Источник истины — здесь, на сервере, а не на клиенте: клиент только
// показывает то, что вернул GET /consents/text, и потом подтверждает
// именно контекст (context), а не сам текст. Так его нельзя подменить.
//
// ВАЖНО: это черновик, а не итоговая юридическая формулировка — Надин это
// известно (обсуждали в чате). Перед реальным запуском для широкой публики
// стоит показать юристу, особенно пункт про 152-ФЗ (там нужны официальные
// реквизиты оператора) и добавить отдельную полноценную Политику обработки
// персональных данных, на которую можно сослаться.
//
// consent_version — дата последней правки текста. Меняется только вместе
// с текстом ниже: старые записи в БД хранят точный текст, который был
// показан в момент согласия, поэтому правки версии их не затрагивают.
const CONSENT_VERSION = '2026-09-03';

const CONSENT_TEXTS = {
  create_listing: `Перед публикацией объявления подтвердите, пожалуйста:

1. Я принимаю личную ответственность за точность указанной информации (цена, объём, время и место выезда) и за качество и безопасность продукции, которую предлагаю.
2. Я понимаю, что «Свежие продукты» — площадка для размещения объявлений, которая не проверяет и не гарантирует качество продукции; вся ответственность за сделку — на мне как на продавце.
3. Я даю согласие на обработку моих персональных данных (имя, Telegram-профиль, данные объявления) в целях работы сервиса — в соответствии с 152-ФЗ «О персональных данных».
4. Если я прикладываю к объявлению фотографии, я подтверждаю, что имею право их использовать, и даю согласие на их публикацию в мини-приложении «Свежие продукты».

Нажимая «Да, подтверждаю», вы соглашаетесь с этими условиями. Факт и время согласия сохраняются.`,

  contact_seller: `Прежде чем написать продавцу, подтвердите, пожалуйста:

1. Я понимаю, что «Свежие продукты» — площадка для знакомства покупателя и продавца и не является стороной сделки; проверка продукции и договорённости о встрече — моя личная ответственность.
2. Я принимаю личную ответственность за своё здоровье при употреблении приобретённых продуктов, а также за сохранность своих вещей при личной встрече с продавцом.
3. Я даю согласие на обработку моих персональных данных (имя, Telegram-профиль, история обращений в мини-приложении) в целях работы сервиса — в соответствии с 152-ФЗ «О персональных данных».
4. Фотографии в объявлении, если они есть, опубликованы с согласия продавца и служат только иллюстрацией.

Нажимая «Да, подтверждаю», вы соглашаетесь с этими условиями. Факт и время согласия сохраняются.`,
};

// ── Текст согласия для конкретного контекста ────────────────────────────
consentsRouter.get('/text', (req, res) => {
  const { context } = req.query;
  const text = CONSENT_TEXTS[context];
  if (!text) return res.status(400).json({ error: 'неизвестный контекст согласия' });
  res.json({ context, version: CONSENT_VERSION, text });
});

// ── Зафиксировать согласие ───────────────────────────────────────────────
// Пишем IP и User-Agent запроса — вместе с полным текстом и telegram_id это
// и есть то самое доказательство, что «в такой-то момент такой-то человек
// согласился именно с этим текстом» (см. requireAdmin-эндпоинт экспорта в
// analytics.js — там всё это можно выгрузить).
consentsRouter.post('/', requireTelegramAuth, async (req, res) => {
  const { context, listing_id } = req.body;
  const text = CONSENT_TEXTS[context];
  if (!text) return res.status(400).json({ error: 'неизвестный контекст согласия' });

  const ip = (req.get('x-forwarded-for') || req.ip || '').split(',')[0].trim() || null;
  const userAgent = req.get('user-agent') || null;

  const { rows } = await pool.query(
    `insert into consents
       (user_id, telegram_id, context, listing_id, consent_version, consent_text, ip_address, user_agent)
     values ($1, $2, $3, $4, $5, $6, $7, $8)
     returning id, created_at`,
    [req.user.id, req.user.telegram_id, context, listing_id || null, CONSENT_VERSION, text, ip, userAgent]
  );

  res.status(201).json(rows[0]);
});
